#!/usr/bin/env python3
"""Finite B210-only standalone TX or RX of AIS complex64 IQ (GNU Radio 3.8/3.10).

TX: Synthetic AIS IQ already generated by the plugin; a finite UHD file-sink
operation at a non-maritime laboratory frequency. RX: UHD capture to complex64,
then the AIS Action passes the file to its existing gr-ais decoder.

CAUTION: UHD gain is NOT an absolute power level. With a cable directly between
TX/RX and RX2, high gain may permanently damage the USRP. Use measured physical
attenuation and verify receiver power limits. Never attach antennas when
running a laboratory transmitter without authorization.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import math
from pathlib import Path
from ais_b210_frontend_v097 import configure_subdevice, validate_antenna
import signal
import sys
import tempfile
import time

# This module can be imported by FISSURE's long-running Sensor Node after a
# plugin upgrade.  Importing by the ordinary module name could pick up an older
# ais_b210_rf_hardware from sys.modules, even when the current file is on disk.
# Load an isolated snapshot from the *same installed plugin directory* instead.
def _load_b210_rf_helpers():
    helper_path = Path(__file__).resolve().with_name("ais_b210_rf_hardware.py")
    if not helper_path.is_file():
        raise ImportError("Missing AIS B210 hardware helper: %s" % helper_path)
    spec = importlib.util.spec_from_file_location(
        "_fissure_ais_standalone_b210_helper", str(helper_path))
    if spec is None or spec.loader is None:
        raise ImportError("Could not load AIS B210 hardware helper: %s" % helper_path)
    helper = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(helper)
    required = ("TX_DIGITAL_SCALE", "probe", "prepare_tx_file", "verify_iq_file")
    missing = [name for name in required if not hasattr(helper, name)]
    if missing:
        raise ImportError("AIS B210 hardware helper at %s is missing: %s; "
                          "install the complete AIS plugin release" %
                          (helper_path, ", ".join(missing)))
    return helper


_b210_helper = _load_b210_rf_helpers()
TX_DIGITAL_SCALE = _b210_helper.TX_DIGITAL_SCALE
probe = _b210_helper.probe
prepare_tx_file = _b210_helper.prepare_tx_file
verify_iq_file = _b210_helper.verify_iq_file


def validate_tx(rate, rf_frequency, tx_gain, device_args):
    rate = int(float(rate))
    freq = float(rf_frequency)
    gain = float(tx_gain)
    if not 192000 <= rate <= 960000 or rate % 48000:
        raise ValueError("TX sample rate must be 192-960 kHz, multiple of 48 kHz")
    if not math.isfinite(freq) or not 500e6 <= freq <= 3000e6:
        raise ValueError("TX must use a non-maritime lab frequency between 500 MHz and 3 GHz")
    if not math.isfinite(gain) or gain < 0:
        raise ValueError("TX gain must be finite and nonnegative; UHD enforces device limits")
    if any(c in str(device_args) for c in "\r\n\x00"):
        raise ValueError("Invalid UHD device args")
    return rate


def validate_rx(rate, rf_frequency, rx_gain, device_args, duration):
    rate = int(float(rate))
    freq = float(rf_frequency)
    gain = float(rx_gain)
    duration = float(duration)
    if not 192000 <= rate <= 960000 or rate % 48000:
        raise ValueError("RX sample rate must be 192-960 kHz, multiple of 48 kHz")
    if not math.isfinite(freq) or not 70e6 <= freq <= 3000e6:
        raise ValueError("RX frequency must be 70 MHz-3 GHz")
    if not math.isfinite(gain) or gain < 0:
        raise ValueError("RX gain must be finite and nonnegative; UHD enforces device limits")
    if not math.isfinite(duration) or not 1 <= duration <= 120:
        raise ValueError("Capture duration must be 1-120 seconds")
    if any(c in str(device_args) for c in "\r\n\x00"):
        raise ValueError("Invalid UHD device args")
    return rate


def make_tx_graph(iq_path, rate, freq, device, gain, runtime, rf_channel=0):
    gr, blocks, uhd, _ = runtime
    stream_args = uhd.stream_args(cpu_format="fc32", channels=[0])
    tx = uhd.usrp_sink(device, stream_args)
    configure_subdevice(tx, 'tx', rf_channel)
    tx.set_samp_rate(rate)
    if abs(float(tx.get_samp_rate()) - rate) > 1:
        raise RuntimeError("UHD TX rate does not match IQ sample rate")
    tx.set_center_freq(freq, 0)
    tx.set_gain(gain, 0)
    tx.set_antenna("TX/RX", 0)
    src = blocks.file_source(gr.sizeof_gr_complex, str(iq_path), False)
    scale = blocks.multiply_const_cc(TX_DIGITAL_SCALE)
    tb = gr.top_block("FISSURE AIS standalone B210 TX")
    tb.connect((src, 0), (scale, 0), (tx, 0))
    return tb


def make_rx_graph(output_path, samples, rate, freq, device, gain, runtime, rf_channel=0, rx_antenna='TX/RX'):
    gr, blocks, uhd, _ = runtime
    stream_args = uhd.stream_args(cpu_format="fc32", channels=[0])
    rx = uhd.usrp_source(device, stream_args)
    configure_subdevice(rx, 'rx', rf_channel)
    rx.set_samp_rate(rate)
    if abs(float(rx.get_samp_rate()) - rate) > 1:
        raise RuntimeError("UHD RX rate does not match recorded sample rate")
    rx.set_center_freq(freq, 0)
    rx.set_gain(gain, 0)
    rx.set_antenna(validate_antenna(rx_antenna), 0)
    limiter = blocks.head(gr.sizeof_gr_complex, int(samples))
    sink = blocks.file_sink(gr.sizeof_gr_complex, str(output_path), False)
    tb = gr.top_block("FISSURE AIS standalone B210 RX")
    tb.connect((rx, 0), (limiter, 0), (sink, 0))
    return tb, sink


def _run_bounded(tb, seconds):
    # The UHD source/sink can remain active after a finite file source ends;
    # match the approach already validated for the combined B210 Action.
    started = False
    prior = signal.getsignal(signal.SIGTERM)
    def interrupted(signum, frame):
        if started:
            tb.stop()
        raise KeyboardInterrupt("AIS SDR operation interrupted")
    signal.signal(signal.SIGTERM, interrupted)
    try:
        tb.start()
        started = True
        time.sleep(seconds)
        tb.stop()
        tb.wait()
    finally:
        signal.signal(signal.SIGTERM, prior)
        if started:
            tb.stop()
            tb.wait()


def run_tx(input_file, manifest_file, rate=240000, frequency=915000000,
           device="type=b200", gain=60, rf_channel=0):
    rate = validate_tx(rate, frequency, gain, device)
    path, _ = verify_iq_file(input_file)
    runtime = probe()
    result_path = Path(manifest_file).expanduser().resolve()
    result_path.parent.mkdir(parents=True, exist_ok=True)
    result_path.unlink(missing_ok=True)
    with tempfile.TemporaryDirectory(prefix="fissure_ais_standalone_tx_") as scratch:
        padded = Path(scratch) / "tx_finite.cf32"
        leading, trailing, samples = prepare_tx_file(path, padded, rate, lead_s=1.0, tail_s=0.5)
        tb = make_tx_graph(padded, rate, float(frequency), str(device), float(gain), runtime, rf_channel)
        _run_bounded(tb, samples / rate + 1.0)
    result = {
        "schema": "fissure.ais.sdr_tx.v1", "device": "USRP B210",
        "rf_transmitted": True, "lab_frequency_hz": float(frequency),
        "sample_rate_hz": rate, "tx_gain_db": float(gain),
        "tx_digital_amplitude": TX_DIGITAL_SCALE, "transmitted_samples": samples,
        "leading_samples": leading, "trailing_samples": trailing,
        "source_file": str(path), "rx_input_power_measured": False,
        "physical_attenuation_verified_by_software": False,
    }
    result_path.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    return result


def run_rx(output_file, manifest_file, rate=240000, frequency=162000000,
           device="type=b200", gain=70, duration=20, rf_channel=0, rx_antenna='TX/RX'):
    rate = validate_rx(rate, frequency, gain, device, duration)
    runtime = probe()
    output_path = Path(output_file).expanduser().resolve()
    manifest_path = Path(manifest_file).expanduser().resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    partial = output_path.with_name(output_path.name + ".partial")
    partial.unlink(missing_ok=True)
    output_path.unlink(missing_ok=True)
    manifest_path.unlink(missing_ok=True)
    samples = int(rate * float(duration))
    try:
        tb, sink = make_rx_graph(partial, samples, rate, float(frequency), str(device), float(gain), runtime, rf_channel, rx_antenna)
        _run_bounded(tb, float(duration) + 1.0)
        try:
            sink.close()
        except AttributeError:
            pass
        if not partial.is_file() or partial.stat().st_size < 8192 or partial.stat().st_size % 8:
            raise RuntimeError("B210 RX produced no valid complex64 samples")
        received = partial.stat().st_size // 8
        if received < int(samples * .95):
            raise RuntimeError("B210 RX capture incomplete: %d/%d samples" % (received, samples))
        partial.replace(output_path)
        result = {
            "schema": "fissure.ais.sdr_rx.v1", "device": "USRP B210",
            "rf_transmitted": False, "rf_center_frequency_hz": float(frequency),
            "sample_rate_hz": rate, "rx_gain_db": float(gain),
            "rx_antenna": validate_antenna(rx_antenna), "samples_received": received,
            "capture_path": str(output_path), "duration_s": float(duration),
            "ais_positions_are_self_reported": True,
        }
        manifest_path.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
        return result
    finally:
        partial.unlink(missing_ok=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description="FISSURE standalone B210 AIS TX/RX helper")
    parser.add_argument("--probe", action="store_true")
    parser.add_argument("--mode", choices=["tx", "rx"])
    parser.add_argument("--input")
    parser.add_argument("--output")
    parser.add_argument("--manifest")
    parser.add_argument("--sample-rate", type=int, default=240000)
    parser.add_argument("--rf-frequency", type=float)
    parser.add_argument("--device-args", default="type=b200")
    parser.add_argument("--rf-channel", default="0")
    parser.add_argument("--rx-antenna", default="TX/RX")
    parser.add_argument("--tx-gain", type=float, default=60)
    parser.add_argument("--rx-gain", type=float, default=70)
    parser.add_argument("--duration-s", type=float, default=20)
    args = parser.parse_args(argv)
    try:
        if args.probe:
            print("AIS standalone B210 UHD readiness OK: GNU Radio %s (NO RF)" % probe()[-1])
            return 0
        if args.mode == "tx":
            if not args.input or not args.manifest:
                parser.error("TX requires --input and --manifest")
            info = run_tx(args.input, args.manifest, args.sample_rate,
                          args.rf_frequency if args.rf_frequency is not None else 915e6,
                          args.device_args, args.tx_gain, args.rf_channel)
            print("AIS TX finished: %d samples (RF TX occurred)" % info["transmitted_samples"])
        elif args.mode == "rx":
            if not args.output or not args.manifest:
                parser.error("RX requires --output and --manifest")
            info = run_rx(args.output, args.manifest, args.sample_rate,
                          args.rf_frequency if args.rf_frequency is not None else 162e6,
                          args.device_args, args.rx_gain, args.duration_s, args.rf_channel, args.rx_antenna)
            print("AIS RX finished: %d complex samples" % info["samples_received"])
        else:
            parser.error("--mode is required unless --probe is used")
        return 0
    except KeyboardInterrupt:
        print("AIS standalone SDR operation interrupted", file=sys.stderr)
        return 130
    except Exception as exc:
        print("AIS standalone SDR error: %s: %s" % (type(exc).__name__, exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
