def test_loopback_ignores_stale_sensor_node_helper_modules(monkeypatch):
    """Regression: installing v0.5 after v0.4 without restarting SensorNode.

    Old imported helper modules can survive on sys.modules even though their
    file path now points to a newer implementation on disk.
    """
    from test_ais_plugin import import_operations
    import_operations(monkeypatch)
    for name, file in (
        ("ais_codec", ROOT / "scripts" / "ais_codec.py"),
        ("ais_receive", ROOT / "operations" / "ais_receive.py"),
        ("ais_iq_receive", ROOT / "operations" / "ais_iq_receive.py"),
    ):
        obsolete = types.ModuleType(name)
        obsolete.__file__ = str(file)
        obsolete.FISSURE_AIS_API_REVISION = "ais-plugin-legacy-0.4.4"
        monkeypatch.setitem(sys.modules, name, obsolete)
    assert not hasattr(sys.modules["ais_codec"], "encode_class_b_static")

    updated = load_module(ROOT / "operations" / "ais_iq_loopback.py", "ais_iq_loopback_hot_upgrade")
    assert callable(updated.encode_class_b_static)
    assert updated.FISSURE_AIS_API_REVISION == "ais-plugin-2026-11-10-v1.0"
    for name in ("ais_codec", "ais_receive", "ais_iq_receive"):
        assert sys.modules[name].FISSURE_AIS_API_REVISION == updated.FISSURE_AIS_API_REVISION
    # Verify that the dynamic class graph also inherits the NEW receive module.
    assert updated.OperationMain.__bases__[0] is sys.modules["ais_iq_receive"].OperationMain
    assert sys.modules["ais_iq_receive"].OperationMain.__bases__[0] is sys.modules["ais_receive"].OperationMain


