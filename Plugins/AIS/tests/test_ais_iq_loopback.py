def test_historical_type24_part_a_and_b_are_single_slot_radio_frames():
    """MOTT reference samples include 160-bit A and 168-bit B messages."""
    from ais_iq_generator import nmea_single_slot_frame
    examples = [
        "!AIVDO,1,1,,B,H1c2;qA@PU>0U>060<h5=>0:1Dp,2*7D",
        "!AIVDO,1,1,,B,H1c2;qDTijklmno31<<C970`43<1,0*28",
    ]
    for frame, bits in zip(examples, (160, 168)):
        parsed = nmea_single_slot_frame(frame)
        assert parsed["message_type"] == 24
        assert parsed["mmsi"] == "112233445"
        assert len(parsed["bits"]) == bits
        slot = build_slot(parsed["bits"])
        serial = nrzi_decode("".join(format(v, "08b") for v in slot))
        end = serial.find("01111110", 40)
        decoded = _destuff(serial[40:end])
        assert to_on_air_octet_order(decoded[:bits]) == parsed["bits"]
        assert int(decoded[bits:bits + 16][::-1], 2) == x25_fcs(decoded[:bits])


