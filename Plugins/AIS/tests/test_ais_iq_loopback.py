def test_crc16_x25_known_check_vector():
    # ISO HDLC/X.25: feed octets least-significant-bit-first.
    check_bits = "".join(format(octet, "08b")[::-1] for octet in b"123456789")
    assert x25_fcs(check_bits) == 0x906E


def _unpack_slot(slot):
    encoded = "".join(format(value, "08b") for value in slot)
    return nrzi_decode(encoded)


def _destuff(data):
    out = []
    ones = 0
    index = 0
    while index < len(data):
        bit = data[index]
        out.append(bit)
        ones = ones + 1 if bit == "1" else 0
        index += 1
        if ones == 5:
            assert data[index] == "0"
            index += 1
            ones = 0
    return "".join(out)


def test_finite_slot_fcs_stuffing_and_nrzi_roundtrip():
    fixture = ROOT / "resources" / "demo_3_vessels_5_updates.nmea"
    frames, _ = collect_frames(str(fixture), 24)
    for frame in frames:
        slot = build_slot(frame["bits"])
        assert len(slot) == 32
        decoded = _unpack_slot(slot)
        assert decoded.startswith("01" * 16 + "01111110")  # ramp, training, start
        end = decoded.find("01111110", 40)
        assert end > 40
        payload_fcs = _destuff(decoded[40:end])
        assert len(payload_fcs) == 184
        # OTA HDLC serializes each octet LSB-first. Emulate gr-ais 3.8
        # HDLC deframing and require exact agreement with the source NMEA.
        assert payload_fcs[:168] == to_on_air_octet_order(frame["bits"])
        decoded_octets = to_on_air_octet_order(payload_fcs[:168])
        assert decoded_octets == frame["bits"]
        appended_fcs = int(payload_fcs[168:][::-1], 2)
        assert appended_fcs == x25_fcs(payload_fcs[:168])
    import pytest
    with pytest.raises(ValueError, match="exceeds"):
        build_slot("1" * 168)


def test_real_gr_ais_observation_exposes_octet_bit_order_bug():
    """Regression: v0.4.3 output had every octet reversed, not random noise."""
    expected = nmea_position_frame(
        "!AIVDM,1,1,,A,12vg20@P0tG?pF0EWrD1GQ600000,0*19"
    )["bits"]
    observed = (
        "!AIVDM,1,1,,A,8?Cm4204h:?kQhJ`vJF0N`P10000,0*1D"
    )
    payload = observed.split(",")[5]
    unpacked = "".join(format(ord(c) - 48 - (8 if ord(c) - 48 > 40 else 0), "06b")
                       for c in payload)
    assert unpacked == to_on_air_octet_order(expected)
    # Frames generated by v0.4.4 must be octet-reversed ON AIR so the
    # LSB-first HDLC deframer reconstructs the original AIS payload.
    slot = build_slot(expected)
    decoded = nrzi_decode("".join(format(v, "08b") for v in slot))
    end = decoded.find("01111110", 40)
    deframe = _destuff(decoded[40:end])
    assert to_on_air_octet_order(deframe[:168]) == expected


def test_finite_slot_gmsk_modulation_wiring_and_iq_file(monkeypatch, tmp_path):
    """One finite GNU Radio graph per burst, strict GNU Radio 3.8 rotator API."""
    import struct
    from ais_iq_generator import generate
    calls = {"mod": [], "rot": [], "graphs": [], "source": []}

    class FakeGR:
        sizeof_char = 1
        sizeof_gr_complex = 8

        @staticmethod
        def top_block(label):
            class Graph:
                def __init__(self):
                    self.edges = []
                def connect(self, a, b):
                    self.edges.append((a, b))
                def run(self):
                    sink = [end[0] for _start, end in self.edges
                            if isinstance(end, tuple) and end[0][0] == "sink"][0]
                    Path(sink[1]).write_bytes(struct.pack("<ff", 0.8, 0.2) * 6400)
            result = Graph()
            calls["graphs"].append((label, result))
            return result

    class FakeBlocks:
        @staticmethod
        def vector_source_b(data, repeat):
            calls["source"].append((bytes(data), repeat))
            return ("source", data)
        @staticmethod
        def rotator_cc(angle):
            calls["rot"].append(angle)
            return ("rot", angle)
        @staticmethod
        def file_sink(size, path, flags):
            return ("sink", path)

    class FakeDigital:
        @staticmethod
        def gmsk_mod(**kwargs):
            calls["mod"].append(kwargs)
            return ("gmsk", kwargs)

    import ais_iq_generator as module
    monkeypatch.setattr(module, "probe", lambda: (FakeGR, FakeBlocks, FakeDigital, "3.8.mock"))
    fixture = ROOT / "resources" / "demo_3_vessels_5_updates.nmea"
    iq = tmp_path / "stimulus.cf32"
    manifest_path = tmp_path / "manifest.json"
    result = generate(str(fixture), str(iq), gap_ms=150, max_frames=2, manifest_file=str(manifest_path))
    assert result["frame_count"] == 2
    assert result["rf_transmitted"] is False
    assert len(calls["graphs"]) == 2
    assert all("modulation" in name for name, _ in calls["graphs"])
    frames, _ = collect_frames(str(fixture), 2)
    assert calls["source"] == [(build_slot(frame["bits"]), False) for frame in frames]
    assert all(options["samples_per_symbol"] == 25 and options["bt"] == 0.4
               for options in calls["mod"])
    assert calls["rot"][0] == pytest.approx(-2 * 3.141592653589793 * 25000 / 240000)
    assert calls["rot"][1] == pytest.approx(2 * 3.141592653589793 * 25000 / 240000)
    assert iq.stat().st_size == result["iq_bytes"]
    assert not iq.with_name(iq.name + ".partial").exists()
    assert json.loads(manifest_path.read_text())["frame_count"] == 2


def test_rejects_zero_iq_and_partial_does_not_publish(monkeypatch, tmp_path):
    """A failed burst must never leave a 350ms zero-only .cf32 Artifact."""
    import ais_iq_generator as module
    monkeypatch.setattr(module, "probe", lambda: object())

    def fail_on_first_burst(*args, **kwargs):
        raise RuntimeError("simulated GNU Radio modulation stall")

    monkeypatch.setattr(module, "generate_burst", fail_on_first_burst)
    fixture = ROOT / "resources" / "demo_3_vessels_5_updates.nmea"
    output = tmp_path / "stimulus.cf32"
    with pytest.raises(RuntimeError, match="stall"):
        module.generate(str(fixture), str(output), max_frames=1)
    assert not output.exists()
    assert not output.with_name(output.name + ".partial").exists()


